from enum import StrEnum


class Language(StrEnum):
    """
    Язык отображаемого имени города в автокомплите.

    Закрытое множество поддерживаемых языков газеттира: имена импортируются только
    для ``en``/``ru`` (см. скрипт импорта). Используется как тип query-параметра
    ``lang`` на границе HTTP и как ключ резолва имени в ``City.display_name``.
    """

    EN = "en"
    RU = "ru"
